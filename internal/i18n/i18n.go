var (
	zh    map[string]string
	en    map[string]string
	jaMap map[string]string
)

func init() {
	zh = make(map[string]string, len(pairs))
	en = make(map[string]string, len(pairs))
	jaMap = make(map[string]string, len(pairs))
	for _, p := range pairs {
		zh[p.key] = p.zh
		en[p.key] = p.en
		jaMap[p.key] = p.ja
	}
}

// T returns the string for key in lang. Unknown languages use English.
func T(lang, key string) string {
	table := en
	switch lang {
	case ZhHant:
		table = zh
	case Ja:
		table = jaMap
	}
	if s, ok := table[key]; ok {
		return s
	}
	if s, ok := en[key]; ok {
		return s
	}
	return key
}

// Parity reports an empty string, a duplicate key, or a map that drifted
// from the pair list.
func Parity() error {
	seen := map[string]bool{}
	for _, p := range pairs {
		if p.key == "" || p.zh == "" || p.en == "" || p.ja == "" {
			return fmt.Errorf("i18n: empty catalog entry %q", p.key)
		}
		if seen[p.key] {
			return fmt.Errorf("i18n: duplicate key %s", p.key)
		}
		seen[p.key] = true
		if zh[p.key] != p.zh || en[p.key] != p.en || jaMap[p.key] != p.ja {
			return fmt.Errorf("i18n: map mismatch %s", p.key)
		}
	}
	if len(zh) != len(pairs) || len(en) != len(pairs) || len(jaMap) != len(pairs) {
		return fmt.Errorf("i18n: catalog length zh=%d en=%d ja=%d pairs=%d", len(zh), len(en), len(jaMap), len(pairs))
	}
	return nil
}

// Default follows the operating system. Chinese locales use Traditional Chinese
// and Japanese locales use Japanese.
func Default() string {
	for _, env := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		v := os.Getenv(env)
		if isChinese(v) {
			return ZhHant
		}
		if isJapanese(v) {
			return Ja
		}
	}
	loc := osLocale()
	if isChinese(loc) {
		return ZhHant
	}
	if isJapanese(loc) {
		return Ja
	}
	return En
}

func isChinese(s string) bool {
	s = strings.ToLower(strings.TrimSpace(s))
	if s == "" || s == "c" || s == "posix" {
		return false
	}
	return strings.HasPrefix(s, "zh") || strings.Contains(s, "chinese")
}

func isJapanese(s string) bool {
	s = strings.ToLower(strings.TrimSpace(s))
	if s == "" || s == "c" || s == "posix" {
		return false
	}
	return strings.HasPrefix(s, "ja") || strings.Contains(s, "japanese")
}
